/**
 * Shared types for the SharePoint API research toolkit.
 *
 * Everything in this folder is intentionally free of SPFx / PnPjs imports so
 * that request construction, payload generation and reporting can be unit
 * tested in plain Node (see tests/research/run.ts).
 */

/** Which API surface a request targets. Conventions differ between these. */
export type ApiFamily = "sharepoint-rest" | "sharepoint-v2" | "microsoft-graph";

/** HTTP verbs used by SharePoint. MERGE is a SharePoint convention. */
export type HttpMethod =
  | "GET"
  | "POST"
  | "PATCH"
  | "PUT"
  | "DELETE"
  | "HEAD"
  | "OPTIONS"
  | "MERGE";

/** Where a parameter is transmitted. */
export type ParamLocation = "path" | "query" | "body" | "header";

/** Coarse parameter types used for validation and documentation. */
export type ParamType =
  | "string"
  | "guid"
  | "int"
  | "bool"
  | "date"
  | "enum"
  | "json"
  | "binary"
  | "path";

/** How we know a parameter exists. Never promote a guess to "documented". */
export type EvidenceKind =
  | "msdocs"
  | "pnpjs-source"
  | "pnpjs-typedef"
  | "project-code"
  | "observed-traffic"
  | "hypothesis";

/** Verification level of a single parameter / endpoint definition. */
export type VerificationStatus =
  | "documented"
  | "verified-in-library"
  | "observed"
  | "unverified";

/** Security test families supported by the payload generator. */
export type PayloadFamily =
  | "idor"
  | "mass-assignment"
  | "odata-injection"
  | "xss"
  | "sqli"
  | "ssrf"
  | "path-traversal"
  | "method-confusion"
  | "business-logic"
  | "input-validation"
  | "authz";

/** A generated test is either documented, a controlled probe or a hypothesis. */
export type TestClassification =
  | "documented"
  | "controlled-probe"
  | "hypothesis";

/** Lifecycle of a manual test case. These must stay distinct. */
export type ExecutionStatus =
  | "not-run"
  | "executed"
  | "interesting"
  | "inconclusive"
  | "verified";

/** Authentication / authorisation model needed by an endpoint. */
export type AuthMode =
  | "cookie"
  | "cookie+digest"
  | "bearer-graph";

export interface EndpointParameter {
  name: string;
  location: ParamLocation;
  type: ParamType;
  required: boolean;
  description: string;
  /** Example value that is safe to commit (no tenant secrets). */
  example?: string | number | boolean;
  allowedValues?: Array<string | number>;
  source: EvidenceKind;
  verification: VerificationStatus;
}

export interface RequestBodyDefinition {
  /** Content-Type the service expects for this body. */
  contentType: string;
  /** OData verbose type name, e.g. "SP.Data.TasksListItem". */
  odataType?: string;
  description: string;
  example?: unknown;
  /** Properties the service documents as required. */
  requiredProperties?: string[];
  /** Properties that must never be client-settable (mass-assignment checks). */
  protectedProperties?: string[];
}

export interface EndpointDefinition {
  id: string;
  family: ApiFamily;
  module: string;
  operation: string;
  /** Declared methods. Probe-only methods are generated by variations.ts. */
  methods: HttpMethod[];
  /**
   * URL template relative to the site URL for SharePoint, absolute for Graph.
   * Placeholders use {name} or {name:modifier}:
   *   raw           insert value unchanged
   *   odata         wrap in single quotes and escape embedded quotes
   *   odataEncoded  odata literal, then URL-encoded (for @alias query values)
   *   guid          guid'...'
   *   path          URL-encoded path segment
   */
  urlTemplate: string;
  description: string;
  parameters: EndpointParameter[];
  requestBody?: RequestBodyDefinition;
  /** Headers the service requires in addition to the defaults. */
  requiredHeaders?: string[];
  auth: AuthMode;
  requiresDigest: boolean;
  destructive: boolean;
  /** Whether the service documents ETag / If-Match behaviour. */
  conditional: boolean;
  payloadFamilies: PayloadFamily[];
  sources: EvidenceKind[];
  notes?: string;
}

/** Serialisable query value. Arrays mean "repeat" except OData list options. */
export type QueryValue = string | number | boolean | Array<string | number | boolean>;

export interface QueryPair {
  name: string;
  value: QueryValue;
  /** Do not percent-encode the value (used to reproduce malformed input). */
  raw?: boolean;
}

export type ODataMode = "verbose" | "minimal" | "nometadata";

export interface BuildRequestInput {
  /** Site/web URL, e.g. https://contoso.sharepoint.com/sites/team. */
  siteUrl?: string;
  /** Path placeholder values, keyed by placeholder name. */
  path?: Record<string, string | number>;
  /** Convenience query map. Key order is preserved. */
  query?: Record<string, QueryValue>;
  /** Exact query pairs, preserves duplicates and ordering. */
  queryPairs?: QueryPair[];
  /** Trailing raw query string without the leading "?". */
  rawQuery?: string;
  body?: unknown;
  /** Override the endpoint's declared method (probe usage). */
  method?: HttpMethod;
  /** Additional / overriding headers. */
  headers?: Record<string, string>;
  /** Digest value. Placeholder is used when omitted. */
  digest?: string;
  odataMode?: ODataMode;
  ifMatch?: string;
  ifNoneMatch?: string;
  /** Percent-encode query values. Default true; false reproduces bad encoding. */
  encodeQueryValues?: boolean;
  /** Emit {{REQUEST_DIGEST}} instead of hiding the digest header. Default true. */
  digestPlaceholder?: boolean;
  /** Send MERGE as POST + X-HTTP-Method. Default true (SharePoint convention). */
  useMethodOverride?: boolean;
  /** Default If-Match value for destructive requests. Default "*". */
  defaultIfMatch?: string;
}

export interface HttpRequestSpec {
  method: HttpMethod;
  /** Original verb even when sent via X-HTTP-Method override. */
  intendedMethod: HttpMethod;
  url: string;
  headers: Record<string, string>;
  body?: string;
  endpointId: string;
  family: ApiFamily;
  requiresDigest: boolean;
  destructive: boolean;
  /** Explanation of non-obvious transformations (override, placeholder...). */
  buildNotes: string[];
}

export interface TransportResponse {
  status: number;
  statusText?: string;
  headers: Record<string, string>;
  bodyText: string;
}

export type Transport = (spec: HttpRequestSpec) => Promise<TransportResponse>;

export type ResponseClass =
  | "success"
  | "validation"
  | "authn"
  | "authz"
  | "conflict"
  | "not-found"
  | "throttled"
  | "transient"
  | "unexpected"
  | "network";

export interface AttemptRecord {
  attempt: number;
  status: number;
  responseClass: ResponseClass;
  durationMs: number;
  digestRefreshed: boolean;
}

export interface ExecutionRecord {
  endpointId: string;
  method: HttpMethod;
  url: string;
  status: number;
  responseClass: ResponseClass;
  durationMs: number;
  attempts: AttemptRecord[];
  /** Redacted, truncated response body for manual triage. */
  responsePreview: string;
  /** Redacted response headers. */
  responseHeaders: Record<string, string>;
  startedAt: string;
  error?: string;
}

export interface Payload {
  id: string;
  family: PayloadFamily;
  name: string;
  classification: TestClassification;
  location: ParamLocation;
  /** Target parameter / field / query option. */
  parameter: string;
  value: unknown;
  /** Why the test is relevant and where the suspected sink is. */
  rationale: string;
  /** Response differences worth investigating manually. */
  expectedObservations: string[];
  /** True for the matched benign baseline that should be sent first. */
  control: boolean;
  destructive: boolean;
}

export interface PayloadGenerationContext {
  /** Field or query option to mutate, e.g. "Title". */
  parameter?: string;
  location?: ParamLocation;
  resourceType?:
    | "list"
    | "item"
    | "file"
    | "folder"
    | "attachment"
    | "comment"
    | "user"
    | "group"
    | "search"
    | "unknown";
  /** Known-good value used by the control request. */
  baselineValue?: unknown;
}

export interface RequestChange {
  location: "method" | "path" | "query" | "body" | "header";
  name: string;
  before?: string;
  after?: string;
  note?: string;
}

export interface RequestVariation {
  id: string;
  description: string;
  classification: TestClassification;
  rationale: string;
  changes: RequestChange[];
  request: HttpRequestSpec;
  /** Response differences worth reviewing manually. */
  expectedObservations?: string[];
}

export interface CoverageStatus {
  implemented: boolean;
  generated: boolean;
  executed: boolean;
  verified: boolean;
}

export interface CoverageEndpointRow {
  id: string;
  module: string;
  methods: HttpMethod[];
  status: CoverageStatus;
  payloadFamilies: PayloadFamily[];
}

export interface CoverageReport {
  generatedAt: string;
  endpoints: {
    total: number;
    implemented: number;
    generated: number;
    executed: number;
    verified: number;
  };
  families: Record<string, number>;
  modules: Record<
    string,
    {
      endpoints: number;
      verified: number;
      methods: HttpMethod[];
      payloadFamilies: PayloadFamily[];
    }
  >;
  methods: Record<string, number>;
  payloadFamilies: Record<string, number>;
  statuses: Record<ExecutionStatus, number>;
  rows: CoverageEndpointRow[];
  gaps: string[];
  limitations: string[];
}
