function queryParam(
  name: string,
  description: string,
  example?: string | number | boolean,
  source: EvidenceKind = "msdocs",
  verification: VerificationStatus = "documented"
): EndpointParameter {
  return {
    name: name,
    location: "query",
    type: "string",
    required: false,
    description: description,
    example: example,
    source: source,
    verification: verification,
  };
}

function pathParam(
  name: string,
  type: ParamType,
  description: string,
  example?: string | number | boolean,
  source: EvidenceKind = "msdocs",
  verification: VerificationStatus = "documented"
): EndpointParameter {
  return {
    name: name,
    location: "path",
    type: type,
    required: true,
    description: description,
    example: example,
    source: source,
    verification: verification,
  };
}

function bodyParam(
  name: string,
  description: string,
  type: ParamType = "json",
  source: EvidenceKind = "msdocs",
  verification: VerificationStatus = "documented"
): EndpointParameter {
  return {
    name: name,
    location: "body",
    type: type,
    required: false,
    description: description,
    source: source,
    verification: verification,
  };
}

function jsonBody(
  contentType: string,
  description: string,
  example: unknown,
  options?: {
    odataType?: string;
    requiredProperties?: string[];
    protectedProperties?: string[];
  }
): RequestBodyDefinition {
  return {
    contentType: contentType,
    description: description,
    example: example,
    odataType: options && options.odataType,
    requiredProperties: options && options.requiredProperties,
    protectedProperties: options && options.protectedProperties,
  };
}

function endpoint(def: EndpointDefinition): EndpointDefinition {
  return def;
}

function pascalCaseProperties(source: Record<string, unknown>): Record<string, unknown> {
  const output: Record<string, unknown> = {};
  Object.keys(source).forEach((key) => {
    output[key.charAt(0).toUpperCase() + key.slice(1)] = source[key];
  });
  return output;
}

function catalogEndpoint(
  id: string,
  module: string,
  operation: string,
  methods: HttpMethod[],
  urlTemplate: string,
  description: string,
  parameters: EndpointParameter[],
  destructive: boolean = false,
  requestBody?: RequestBodyDefinition,
  requiredHeaders?: string[]
): EndpointDefinition {
  return endpoint({
    id: id, family: "sharepoint-rest", module: module, operation: operation,
    methods: methods, urlTemplate: urlTemplate, description: description,
    parameters: parameters, requestBody: requestBody, requiredHeaders: requiredHeaders,
    auth: destructive || methods.some((method) => method !== "GET") ? "cookie+digest" : "cookie",
    requiresDigest: destructive || methods.some((method) => method !== "GET"),
    destructive: destructive, conditional: destructive,
    payloadFamilies: ["idor", "authz", "input-validation", "business-logic", "mass-assignment", "method-confusion"],
    sources: ["pnpjs-source"],
  });
}

function fileActionEndpoint(
  id: string,
  operation: string,
  action: string,
  methods: HttpMethod[],
  description: string,
  destructive: boolean,
  actionParameters?: EndpointParameter[]
): EndpointDefinition {
  return endpoint({
    id: id,
    family: "sharepoint-rest",
    module: "files",
    operation: operation,
    methods: methods,
    urlTemplate: "/_api/web/GetFileByServerRelativePath(DecodedUrl=@filePath)/" + action + "?@filePath={filePath:odataEncoded}",
    description: description,
    parameters: [pathParam("filePath", "path", "Configured server-relative document path.", DOCUMENT_FILE_PATH)].concat(actionParameters || []),
    requestBody: actionParameters && actionParameters.some((parameter) => parameter.location === "body")
      ? jsonBody("application/json;odata=verbose", "File operation parameters.", { parameters: {} }, { requiredProperties: ["parameters"] })
      : undefined,
    auth: destructive ? "cookie+digest" : "cookie",
    requiresDigest: destructive,
    destructive: destructive,
    conditional: destructive,
    payloadFamilies: ["idor", "path-traversal", "authz", "input-validation", "business-logic", "method-confusion"],
    sources: ["pnpjs-source", "msdocs", "project-code"],
  });
}

